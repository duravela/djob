test('ending a session with an uncertain review requires explicit confirmation', async ({page}) => {
  await signIn(page);
  const origin = new URL(page.url()).origin;
  const session = await (await page.request.get(origin + '/api/console/v1/session')).json();
  const prepared = await page.request.post(origin + '/api/console/v1/mutations', {headers: {Origin: origin, 'X-Djob-CSRF': session.csrf}, data: {tenant_id: 'alpha', launch: {definition_id: 'unsubmitted-job', definition_revision: '1', run_id: 'never-submitted'}}});
  expect(prepared.ok()).toBeTruthy();
  // Exercise the browser's uncertainty UI without interrupting other scenarios.
  // Transport loss and exact retries are tested against real HTTP in Go tests.
  await page.route('**/api/console/v1/session', async route => {
    const response = await route.fetch();
    const data = await response.json();
    data.pending.state = 'uncertain';
    await route.fulfill({response, json: data});
  }, {times: 1});
  await page.reload();
  await expect(page.locator('#pending-banner')).toContainText('Mutation outcome uncertain');
  await page.getByRole('button', {name: 'Sign out', exact: true}).click();
  await expect(page.getByRole('dialog')).toContainText('does not cancel the controller run');
  await expect(page.getByRole('button', {name: 'Download request', exact: true})).toBeVisible();
  await page.getByRole('button', {name: 'Sign out anyway', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Open your workspace', exact: true})).toBeVisible();
});
