  await page.getByRole('link', {name: 'inventory-hash', exact: true}).click();
  await page.getByRole('button', {name: 'Check workers', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Matching code observed', exact: true})).toBeVisible();
  await expect(page.getByRole('dialog')).toContainText('sha256@1');
  await page.getByRole('button', {name: 'Open workers', exact: true}).click();
  await expect(page.getByRole('heading', {name: 'Workers', exact: true})).toBeVisible();
  await expect(records.locator('tbody')).toContainText('controller-1');
  await expect(records.locator('tbody')).toContainText('sha256@1');
  await expect(page.getByRole('button', {name: 'New worker', exact: true})).toHaveCount(0);
  await page.getByRole('button', {name: 'controller-1', exact: true}).click();
  await expect(page.getByRole('dialog')).toContainText('Local execution tasks');
  await expect(page.getByRole('dialog')).toContainText('steps/v1');
  await page.getByRole('button', {name: 'Close dialog', exact: true}).click();
  await page.screenshot({path: testInfo.outputPath('desktop-workers.png'), fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({path: testInfo.outputPath('mobile-workers.png'), fullPage: true});
  await page.setViewportSize({width: 1280, height: 900});
  await mutate('group-updated', 'put_group', {expected_revision: '1', group: {id: 'inventory-group', runtime: 'future/v2'}});
